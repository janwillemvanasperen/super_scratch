import type { Block, Level } from '../levels/schema';
import type { Player } from '../entities/player';
import type { Run } from '../core/rules';
export type WorldObject = Block & {
  ox: number;
  oy: number;
  alive: boolean;
  opened: boolean;
  vy: number;
  phase: number;
  layoutWidth?: number;
  layoutHeight?: number;
  facing?: number;
  attackUntil?: number;
  defeatedAt?: number;
};
export type WorldHost = {
  level: Level;
  p: Player;
  objects: WorldObject[];
  run: Run;
  powers: Record<string, number>;
  elapsed: number;
  standing?: WorldObject;
  checkpoint: { x: number; y: number };
  say: (text: string, seconds?: number) => void;
  burst: (x: number, y: number, color?: number, n?: number) => void;
  solids: () => WorldObject[];
  hurt: (x: number) => void;
  loseLife: () => void;
};
export type ObjectState = {
  enabled: boolean;
  visible: boolean;
  moving: boolean;
  active: boolean;
  pressed: boolean;
  timer: number;
  routeIndex: number;
  direction: number;
  wait: number;
  collapse: number;
  returnTimer: number;
  vx: number;
  thrown: boolean;
  npcLine: number;
  completed: boolean;
  closePending: boolean;
  motionTime: number;
};
export type Environment = {
  gravity: number;
  speed: number;
  friction: number;
  forceX: number;
  forceY: number;
  driftX: number;
  driftY: number;
  water?: WorldObject;
  ladder?: WorldObject;
};
export type Controls = {
  left: boolean;
  right: boolean;
  up: boolean;
  down: boolean;
  jump: boolean;
  jumpPressed: boolean;
  interact: boolean;
  downPressed: boolean;
};
